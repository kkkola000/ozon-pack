START_B = 104
STOP = 106


def encode_code128b(data: str) -> list[int]:
    """Строка -> список ширин элементов (модулей), начиная с чёрной полосы."""
    values = [START_B]
    for char in data:
        code = ord(char)
        if not 32 <= code <= 126:
            raise ValueError(f"Символ {char!r} не кодируется в Code128B")
        values.append(code - 32)
    checksum = values[0]
    for position, value in enumerate(values[1:], start=1):
        checksum += position * value
    values.append(checksum % 103)
    values.append(STOP)
    widths: list[int] = []
    for value in values:
        widths.extend(int(ch) for ch in PATTERNS[value])
    return widths


def bars(data: str) -> list[tuple[int, int, bool]]:
    """Список (смещение_в_модулях, ширина, чёрный?) — удобно для отрисовки."""
    result = []
    offset = 0
    dark = True
    for width in encode_code128b(data):
        result.append((offset, width, dark))
        offset += width
        dark = not dark
    return result


def total_modules(data: str) -> int:
    return sum(encode_code128b(data))
